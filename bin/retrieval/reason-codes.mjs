const CODE_SET = new Set(Object.values(REASON_CODES));

export function isValidReasonCode(code) {
  return CODE_SET.has(code);
}

export function assertValidReasonCode(code) {
  if (!isValidReasonCode(code)) {
    throw new Error(`Invalid reason code: ${code}. Must be one of: ${[...CODE_SET].join(', ')}`);
  }
}

export function createReasonCodeTracker() {
  const codes = new Set();
  return {
    add(code) {
      assertValidReasonCode(code);
      codes.add(code);
    },
    has(code) {
      return codes.has(code);
    },
    toArray() {
      return [...codes];
    },
    clear() {
      codes.clear();
    }
  };
}
